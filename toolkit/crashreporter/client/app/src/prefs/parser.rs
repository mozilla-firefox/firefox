//! Prefs file parsing utilities.
//!
//! This isn't as extensive as the Rust libpref parser, but we don't need it to be. We _could_
//! potentially use that library, but we're only interested in a subset of prefs so we don't need to
//! parse everything. That doesn't support "lockPref" yet, which I've seen in debian package patches
//! and Enterprise code, though Enterprise hasn't changed libpref.
//!
//! This parsing also permits any pref function to be used in user pref files, whereas the libpref
//! parsing only allows `user_pref`.

const PREF_FUNCTION_NAMES: &[&str] = &["user_pref", "pref", "sticky_pref", "lockPref"];

/// Parse a single pref value (if any) from the prefs file contents.
///
/// This parser could be improved (e.g., it doesn't respect comments), but it is compatible with
/// prefs files generated by Firefox.
///
/// This finds the first string match for the regex `PREF_FUNCTION\("PREFSTRING"[ \t\n\r\f\v,]*(.*)[ \t\n\r\f\v]*\);`.
///
/// For example:
/// ```rust
/// let input = r#"user_pref("FOOBAR", "baz");"#;
/// let expected_output = Some(r#""baz""#);
/// assert_eq!(find_pref(input, "FOOBAR"), expected_output);
/// ```
pub fn find_pref<'a>(prefs_content: &'a str, pref: &str) -> Option<&'a str> {
    let mut search_content = prefs_content;
    loop {
        let (before, s) = search_content.split_once(&format!("\"{pref}\""))?;
        if !is_pref_prefix(before) {
            search_content = s;
            continue;
        }
        let s = s.trim_start_matches(|c: char| c.is_whitespace() || c == ',');
        // Prefs support zero or more attribute constants as additional "arguments". This is very
        // rare, so we don't support that here to keep this parsing simple.
        let (content, _) = s.split_once(");")?;
        return Some(content.trim());
    }
}

fn is_pref_prefix(mut s: &str) -> bool {
    s = s.trim();
    let Some(s) = s.strip_suffix('(') else {
        return false;
    };
    // Get the ending substring that is ascii_alphabetic
    let s = s
        .rsplit_once(|c: char| !c.is_ascii_alphabetic())
        .map(|parts| parts.1)
        .unwrap_or(s);
    PREF_FUNCTION_NAMES.contains(&s)
}

/// Find a single string pref (if any) from the prefs file contents.
///
/// This is very simple, and doesn't account for escape sequences.
pub fn find_string_pref<'a>(prefs_content: &'a str, pref: &str) -> Option<&'a str> {
    find_pref(prefs_content, pref).and_then(|s| s.strip_prefix('"')?.strip_suffix('"'))
}

/// Find a single bool pref (if any) from the prefs file contents.
pub fn find_bool_pref(prefs_content: &str, pref: &str) -> Option<bool> {
    find_pref(prefs_content, pref).and_then(|s| s.parse().ok())
}

// Doctests don't run for binaries, so make some unit tests instead.
#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn find_pref_read_value() {
        let input = r#"user_pref("FOOBAR", "baz");"#;
        assert_eq!(find_pref(input, "FOOBAR"), Some(r#""baz""#));
    }

    #[test]
    fn find_pref_continues_search() {
        let input = r#"
            user_pref("rawr", "FOOBAR");
            user_pref("FOOBAR", "baz");
        "#;
        assert_eq!(find_pref(input, "FOOBAR"), Some(r#""baz""#));
    }

    #[test]
    fn find_pref_missing() {
        let input = r#"
            user_pref("rawr", "FOOBAR");
            user_pref("FOOBAR", "hello");
        "#;
        assert_eq!(find_pref(input, "hello"), None);
    }

    #[test]
    fn test_find_string_pref() {
        let input = r#"user_pref("FOOBAR", "baz");"#;
        assert_eq!(find_string_pref(input, "FOOBAR"), Some("baz"));
    }

    #[test]
    fn pref_functions() {
        assert_eq!(find_pref(r#"user_pref("A", true);"#, "A"), Some("true"));
        assert_eq!(find_pref(r#"pref("A", true);"#, "A"), Some("true"));
        assert_eq!(find_pref(r#"sticky_pref("A", true);"#, "A"), Some("true"));
        assert_eq!(find_pref(r#"lockPref("A", true);"#, "A"), Some("true"));
        assert_eq!(find_pref(r#"somepref("A", true);"#, "A"), None);
    }

    #[test]
    fn test_find_bool_pref() {
        let input = r#"user_pref("FOOBAR", true);"#;
        assert_eq!(find_bool_pref(input, "FOOBAR"), Some(true));
        let input = r#"user_pref("FOOBAR", false);"#;
        assert_eq!(find_bool_pref(input, "FOOBAR"), Some(false));
    }
}
