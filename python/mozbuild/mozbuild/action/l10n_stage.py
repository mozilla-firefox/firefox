"""Per-locale stage action.

Reads <topobjdir>/l10n-manifest.json plus the populated merge tree
at <merge-tree>/ to materialize
<topobjdir>/dist/xpi-stage/locale-<ab_cd>/.

Invoked in make via $(call py_action,l10n_stage,...).
"""

