# Generates the FooJni class that jni_zero would generate for an
# `@NativeMethods interface Natives` nested in class Foo. FooJni implements
# Foo.Natives by forwarding each method to a static native method, optionally
# annotated with @WrapForJNI so C++ can implement it through
# mozilla::java::FooJni::Natives.

import os
import re

NATIVES_RE = re.compile(
    r"@NativeMethods\s+(?:\w+\s+)*interface\s+Natives\s*\{(?P<body>[^{}]*)\}"
)
METHOD_RE = re.compile(
    r"^(?P<ret>.+?)\s+(?P<name>\w+)\s*\((?P<params>.*)\)$", re.DOTALL
)


def strip_comments(source):
    return re.sub(r"//[^\n]*|/\*.*?\*/", "", source, flags=re.DOTALL)


# Turn "int foo, String bar, List<Object> baz" into
# ["int foo", "String bar", "List<Object> baz"].
def split_params(params):
    result = []
    depth = 0
    current = ""
    for c in params:
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
        if c == "," and depth == 0:
            result.append(current)
            current = ""
        else:
            current += c
    if current.strip():
        result.append(current)
    return [" ".join(p.split()) for p in result]


def generate(source, outer, wrap_for_jni):
    source = strip_comments(source)
    package = re.search(r"^package\s+([\w.]+)\s*;", source, re.MULTILINE).group(1)
    imports = [
        i
        for i in re.findall(r"^import\s+[\w.*\s]+;", source, re.MULTILINE)
        if not re.match(r"import\s+org\.jni_zero\.", i)
    ]
    if wrap_for_jni:
        imports.append("import org.mozilla.gecko.annotation.WrapForJNI;")
    # Natives may refer to types nested in the outer class without qualifying.
    imports.append(f"import {package}.{outer}.*;")

    interfaces = NATIVES_RE.findall(source)
    if len(interfaces) != 1:
        raise Exception(
            f"Expected exactly one @NativeMethods interface Natives in {outer}, "
            f"found {len(interfaces)}"
        )

    jni = f"{outer}Jni"
    members = []
    body = " ".join(interfaces[0].split())
    for decl in filter(None, (d.strip() for d in body.split(";"))):
        m = METHOD_RE.match(decl)
        if not m:
            raise Exception(f"Cannot parse {outer}.Natives method: {decl}")
        ret, name, params = m.group("ret"), m.group("name"), m.group("params")
        params = split_params(params)
        args = ", ".join(p.split()[-1] for p in params)
        params = ", ".join(params)
        stub = name[0].upper() + name[1:]
        call = f"native{stub}({args});"
        if not re.fullmatch(r"(@\w+\s+)*void", ret):
            call = "return " + call
        annotation = f'@WrapForJNI(stubName = "{stub}")\n  ' if wrap_for_jni else ""
        members.append(
            f"  @Override\n"
            f"  public {ret} {name}({params}) {{\n"
            f"    {call}\n"
            f"  }}\n"
            f"\n"
            f"  {annotation}private static native {ret} native{stub}({params});\n"
        )

    newline = "\n"
    return f"""// Generated by mobile/android/gen_jni_zero_natives.py. Do not edit.

package {package};

{newline.join(imports)}

class {jni} implements {outer}.Natives {{
  private static final {jni} INSTANCE = new {jni}();

  static {outer}.Natives get() {{
    return INSTANCE;
  }}

{newline.join(members)}}}
"""


def main(output, source_path, *flags):
    outer = os.path.splitext(os.path.basename(source_path))[0]
    with open(source_path, encoding="utf-8") as f:
        output.write(generate(f.read(), outer, "--wrap-for-jni" in flags))
