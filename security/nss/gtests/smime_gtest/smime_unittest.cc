// The prefix of kPfxWithCertBag that ends right after the SafeBag type OID,
// so a bag exists whose content has not been decoded.
static const size_t kPfxCutInsideCertBag = 78;
static const uint8_t kPfxPassword[] = {0, 'p', 0, 'a', 0, 's', 0, 's', 0, 'w',
                                       0, 'o', 0, 'r', 0, 'd', 0, 0};

static SECItem* KeepNickname(SECItem* old_nick, PRBool* cancel, void*) {
  *cancel = PR_FALSE;
  return SECITEM_DupItem(old_nick);
}

static SECStatus NoRename(const CERTCertificate*, const SECItem*,
                          SECItem** new_nick, void*) {
  *new_nick = nullptr;
  return SECSuccess;
}

TEST_F(SMimeTest, Pkcs12DecoderCompletePfxVerifies) {
  std::vector<uint8_t> pw(kPfxPassword, kPfxPassword + sizeof(kPfxPassword));
  SECItem pw_item = {siBuffer, pw.data(), static_cast<unsigned int>(pw.size())};
  SEC_PKCS12DecoderContext* dcx = SEC_PKCS12DecoderStart(
      &pw_item, nullptr, nullptr, nullptr, nullptr, nullptr, nullptr, nullptr);
  ASSERT_NE(nullptr, dcx);
  EXPECT_EQ(SECSuccess,
            SEC_PKCS12DecoderUpdate(dcx, const_cast<uint8_t*>(kPfxWithCertBag),
                                    sizeof(kPfxWithCertBag)));
  EXPECT_EQ(SECSuccess, SEC_PKCS12DecoderVerify(dcx));
  EXPECT_EQ(SECSuccess,
            SEC_PKCS12DecoderRenameCertNicknames(dcx, NoRename, nullptr));
  CERTCertList* certs = SEC_PKCS12DecoderGetCerts(dcx);
  EXPECT_NE(nullptr, certs);
  if (certs) {
    CERT_DestroyCertList(certs);
  }
  SEC_PKCS12DecoderFinish(dcx);
}

// Once Verify has reported that the PFX is incomplete, every later phase
// must refuse to touch the half-decoded bags.
TEST_F(SMimeTest, Pkcs12DecoderTruncatedPfxFailsClosed) {
  SECItem pw_item = {siBuffer, const_cast<uint8_t*>(kPfxPassword),
                     sizeof(kPfxPassword)};
  SEC_PKCS12DecoderContext* dcx = SEC_PKCS12DecoderStart(
      &pw_item, nullptr, nullptr, nullptr, nullptr, nullptr, nullptr, nullptr);
  ASSERT_NE(nullptr, dcx);
  EXPECT_EQ(SECSuccess,
            SEC_PKCS12DecoderUpdate(dcx, const_cast<uint8_t*>(kPfxWithCertBag),
                                    kPfxCutInsideCertBag));
  EXPECT_EQ(SECFailure, SEC_PKCS12DecoderVerify(dcx));
  EXPECT_EQ(SECFailure, SEC_PKCS12DecoderValidateBags(dcx, KeepNickname));
  EXPECT_EQ(SECFailure,
            SEC_PKCS12DecoderRenameCertNicknames(dcx, NoRename, nullptr));
  EXPECT_EQ(nullptr, SEC_PKCS12DecoderGetCerts(dcx));
  EXPECT_EQ(SECFailure, SEC_PKCS12DecoderIterateInit(dcx));
  const SEC_PKCS12DecoderItem* item = nullptr;
  EXPECT_EQ(SECFailure, SEC_PKCS12DecoderIterateNext(dcx, &item));
  EXPECT_EQ(SECFailure, SEC_PKCS12DecoderImportBags(dcx));
  SEC_PKCS12DecoderFinish(dcx);
}

