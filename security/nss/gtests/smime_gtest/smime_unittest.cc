// Content callback: records that the AEAD decrypt ran and captures the
// decrypted plaintext that NSS hands back for the encapsulated content.
struct DecryptedContent {
  bool called = false;
  std::string bytes;
};

static void CaptureDecryptedContent(void* arg, const char* buf,
                                    unsigned long len) {
  auto* out = static_cast<DecryptedContent*>(arg);
  out->called = true;
  out->bytes.append(buf, len);
}

